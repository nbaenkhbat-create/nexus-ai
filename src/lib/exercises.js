export function exercisesBySkill(skill) {
  return EXERCISES.filter((e) => e.skill === skill);
}

export function getExercise(id) {
  return EXERCISES.find((e) => e.id === id) || null;
}

/** Сонголттой дасгалыг үнэлэх: {score(0-100), details:[{ok, explanation}]} */
export function gradeChoiceExercise(exercise, answers) {
  const details = (exercise.questions || []).map((q, i) => {
    const given = answers[i];
    const ok = typeof given === "number" && given === q.answer;
    return { ok: !!ok, given: given ?? null, explanation: q.explanation };
  });
  const right = details.filter((d) => d.ok).length;
  const total = details.length || 1;
  return { score: Math.round((right / total) * 100), details, right, total };
}
